def structural_fsm_analysis(
        module_info
        ):
    """
    ===========================================================
    Structural FSM Analysis

    Builds the complete structural database used by

        • FSM Detection
        • FSM Quality
        • Transition Recovery
        • RTL Agent
        • Dataset Generation

    ===========================================================
    """

    #
    # ---------------------------------------------------------
    # Assignment / Dependency Graph
    # ---------------------------------------------------------
    #

    graph_db = build_assignment_graph( module_info)

    assignment_graph = graph_db.get( "assignment_graph", {})

    dependency_graph = graph_db.get( "dependency_graph", {})

    always_roles = graph_db.get( "always_roles", {})


    # --------------------------------------------------------
    # build_case_database()
    # --------------------------------------------------------

    case_usage = build_case_usage_db(module_info)

    # --------------------------------------------------------
    # build_state_value_db()
    # --------------------------------------------------------
    # ---------------------------------------------------------
    # Symbolic State Database
    # ---------------------------------------------------------

    state_db = build_symbol_db(module_info)

    state_value_db = state_db["state_value_db"]

    symbol_db = state_db["symbol_db"]

    # --------------------------------------------------------
    # generate_state_candidates
    # --------------------------------------------------------

    generate_state_candidates(module_info)

    # -------------------------------------------------------
    # validate_state_candidates
    # ---------------------------------------------------------
    validate_state_candidates(module_info)

    #
    # ---------------------------------------------------------
    # Candidate State Registers
    # ---------------------------------------------------------
    #

    state_scores = score_state_registers(

        module_info,

        assignment_graph,

        dependency_graph,

        always_roles,

        case_usage,

        state_value_db,

        symbol_db

    )

    #
    # ---------------------------------------------------------
    # Select Best State Register
    # ---------------------------------------------------------
    #

    best_state_reg = None

    if state_scores:

        best_state_reg = select_best_state_register( state_scores)

    # --------------------------------------------------------
    # generate_next_state_candidates
    # --------------------------------------------------------
    generate_next_state_candidates( module_info, best_state_reg)

    # ---------------------------------------------------------
    # validate_next_state_candidates
    # ---------------------------------------------------------

    validate_next_state_candidates( module_info, best_state_reg)


    #
    # ---------------------------------------------------------
    # Candidate Next-State Signals
    # ---------------------------------------------------------
    #

    next_scores = score_next_state_signals(

        module_info,

        best_state_reg,

        assignment_graph,

        dependency_graph,

        always_roles,

        case_usage,

        state_value_db,

        symbol_db

    )

    #
    # ---------------------------------------------------------
    # Select Best Next-State
    # ---------------------------------------------------------
    #

    best_next_state = None

    if next_scores:

        # ---------------------------------------------------------
        # Select Best Next-State
        # ---------------------------------------------------------
        
        best_next_state = select_best_next_state(
            next_scores
        )

    #
    # ---------------------------------------------------------
    # FSM Style
    # ---------------------------------------------------------
    #

    style = detect_fsm_style(
        always_roles,
        best_state_reg,
        best_next_state
    )

    # ---------------------------------------------------------
    # select_best_candidates
    # --------------------------------------------------------

    
    # ---------------------------------------------------------
    # detect_style
    # ---------------------------------------------------------


    #
    # ---------------------------------------------------------
    # Confidence
    # ---------------------------------------------------------
    #
    confidence = compute_confidence(
        state_scores,
        best_state_reg,
        best_next_state,
        state_value_db,
        always_roles,
        style
    )


    #
    # ---------------------------------------------------------
    # Return Structural Database
    # ---------------------------------------------------------
    #

    return StructuralFSM(
        #
        # Structural Databases
        #

        assignment_graph=assignment_graph,
    
        dependency_graph=dependency_graph,
    
        always_roles=always_roles,
    
        case_usage=case_usage,
    
        symbol_db=symbol_db,

        #
        # Candidate Scores
        #
    
        state_value_db=state_value_db,
    
        state_scores=state_scores,
    
        next_scores=next_scores,

        #
        # Selected FSM
        #
    
        best_state_reg=best_state_reg,
    
        best_next_state=best_next_state,

        #
        # Classification
        #
    
        style=style,
    
        confidence=confidence,
    )
