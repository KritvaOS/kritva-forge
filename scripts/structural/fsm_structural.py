def generate_state_candidates(module_info):
    """
    Generate possible FSM state register candidates.

    No scoring is performed here.
    Only collect structural evidence.
    """

    structural = module_info.setdefault("structural", {})

    roles = structural.get("always_roles", {})
    assignment_graph = structural.get("assignment_graph", {})
    case_usage = structural.get("case_usage", {})
    state_value_db = structural.get("state_value_db", {})
    reset_assignments = structural.get("reset_assignments", {})

    candidates = []

    signals = module_info.get("signals", [])
    
    roles = structural.get("always_roles", {})
    
    for sig in signals:
    
        #
        # Ignore ports
        #
        if sig.get("direction"):
            continue
    
        name = sig["name"]

        role = get_primary_role( roles, name)
    
        #
        # Only sequential registers
        #
        if role is None:
            continue
    
        if role["type"] != "always_ff":
            continue

        name = sig["name"]

        cand = {

            "signal": name,

            "role": None,

            "width": sig.get("width", 1),

            "evidence": [],

            "features": {},

            "score": 0,

            "valid": False
        }

        #
        # -------------------------------------------------
        # Always role
        # -------------------------------------------------
        #

        if role:

            cand["role"] = role["type"]

            if role["type"] == "always_ff":

                cand["evidence"].append("always_ff")

        #
        # -------------------------------------------------
        # Appears in CASE()
        # -------------------------------------------------
        #

        if name in case_usage:

            cand["evidence"].append("case")

            cand["features"]["case_count"] = \
                case_usage[name]

        #
        # -------------------------------------------------
        # Has enum values
        # -------------------------------------------------
        #

        if name in state_value_db:

            cand["evidence"].append("enum")

            cand["features"]["states"] = \
                state_value_db[name]

        #
        # -------------------------------------------------
        # Reset assignment
        # -------------------------------------------------
        #

        if name in reset_assignments:

            cand["evidence"].append("reset")

        #
        # -------------------------------------------------
        # Assignment graph
        # -------------------------------------------------
        #

        deps = assignment_graph.get(name, [])

        if deps:

            cand["features"]["dependencies"] = deps

            #
            # feedback
            #
            if name in deps:

                cand["evidence"].append("feedback")

            #
            # next-state relation
            #
            if any(

                "_next" in d.lower()

                for d in deps

            ):

                cand["evidence"].append("next_relation")

        #
        # -------------------------------------------------
        # Width
        # -------------------------------------------------
        #

        width = sig.get("width")

        if width:

            cand["features"]["width"] = width

            if width <= 8:

                cand["evidence"].append("small_width")

        #
        # -------------------------------------------------
        # Naming hints
        # -------------------------------------------------
        #

        lname = name.lower()

        if "state" in lname:

            cand["evidence"].append("state_name")

        elif lname.endswith("_st"):

            cand["evidence"].append("state_name")

        elif lname.endswith("_fsm"):

            cand["evidence"].append("state_name")

        candidates.append(cand)

    structural["state_candidates"] = candidates

    return candidates

