def validate_next_state_candidate(candidate,
                                  module_info,
                                  state_candidate=None):
    """
    Validate structural evidence for a next-state signal.

    Parameters
    ----------
    candidate : dict
        Candidate generated by generate_next_state_candidates()

    module_info : dict

    state_candidate : dict | None
        Best validated state register candidate (optional)

    Returns
    -------
    Updated candidate
    """

    structural = module_info.get("structural", {})

    signal = candidate["signal"]

    evidence = set(candidate.get("evidence", []))

    features = candidate.get("features", {})

    required = {

        "always_comb": False,

        "case": False,

        "drives_state": False,

        "width_match": False
    }

    bonus = []

    penalty = []

    #
    # ---------------------------------------------------
    # Required Evidence
    # ---------------------------------------------------
    #

    if "always_comb" in evidence:
        required["always_comb"] = True

    if "case" in evidence:
        required["case"] = True

    if "drives_state" in evidence:
        required["drives_state"] = True

    #
    # ---------------------------------------------------
    # Width check
    # ---------------------------------------------------
    #

    if state_candidate:

        state_width = state_candidate.get("width", 1)

        next_width = candidate.get("width", 1)

        if state_width == next_width:

            required["width_match"] = True

    #
    # ---------------------------------------------------
    # Bonus
    # ---------------------------------------------------
    #

    if "next_name" in evidence:
        bonus.append("next_name")

    if "small_width" in evidence:
        bonus.append("small_width")

    deps = features.get("dependencies", [])

    if deps:

        bonus.append("dependency")

    #
    # ---------------------------------------------------
    # Penalties
    # ---------------------------------------------------
    #

    lname = signal.lower()

    BAD_SUFFIX = (

        "_cnt",
        "_counter",
        "_addr",
        "_data",
        "_mask",
        "_ptr",
        "_crc",
        "_sum",
        "_size",
        "_index"

    )

    if lname.endswith(BAD_SUFFIX):

        penalty.append("datapath_name")

    width = candidate.get("width", 1)

    if width > 16:

        penalty.append("large_width")

    #
    # Arithmetic expression usually indicates datapath
    #

    if any(

        "+" in str(d)
        or
        "-" in str(d)
        or
        "*" in str(d)

        for d in deps

    ):

        penalty.append("arithmetic")

    #
    # ---------------------------------------------------
    # Validation
    # ---------------------------------------------------
    #

    required_count = sum(required.values())

    if required_count >= 3:

        valid = True

        confidence = "high"

    elif required_count == 2 and len(bonus) >= 2:

        valid = True

        confidence = "medium"

    elif required_count == 2:

        valid = True

        confidence = "low"

    else:

        valid = False

        confidence = "reject"

    #
    # Too many penalties
    #

    if len(penalty) >= 2:

        valid = False

        confidence = "reject"

    #
    # Save results
    #

    candidate["valid"] = valid

    candidate["confidence"] = confidence

    candidate["required"] = required

    candidate["bonus"] = bonus

    candidate["penalty"] = penalty

    return candidate

