def generate_next_state_candidates(module_info,best_state_reg):
    """
    Generate next-state candidates.

    No scoring.
    """

    structural = module_info.setdefault("structural", {})

    roles = structural.get("always_roles", {})
    assignment_graph = structural.get("assignment_graph", {})
    case_usage = structural.get("case_usage", {})

    signals = module_info.get("signals", [])

    candidates = []

    for sig in signals:

        if sig.get("direction"):
            continue

        name = sig["name"]


        role = get_primary_role( roles, name)
        
        if role is None:
            continue
        
        if role["type"] != "always_comb":
            continue


        cand = {

            "signal": name,

            "role": None,

            "width": sig.get("width", 1),

            "evidence": [],

            "features": {},

            "score": 0,

            "valid": False
        }





        if role:

            cand["role"] = role["type"]

            if role["type"] == "always_comb":

                cand["evidence"].append("always_comb")

        if name in case_usage:

            cand["evidence"].append("case")

        deps = assignment_graph.get(name, [])

        if deps:

            cand["features"]["dependencies"] = deps

            #
            # drives state register
            #

            if best_state_reg in deps:
                cand["evidence"].append("drives_state")

        lname = name.lower()

        if "next" in lname:

            cand["evidence"].append("next_name")

        elif lname.endswith("_n"):

            cand["evidence"].append("next_name")

        elif lname.endswith("_ns"):

            cand["evidence"].append("next_name")

        elif lname.endswith("_next"):

            cand["evidence"].append("next_name")

        width = sig.get("width")

        if width and width <= 8:

            cand["evidence"].append("small_width")

        candidates.append(cand)

    structural["next_state_candidates"] = candidates

    return candidates

