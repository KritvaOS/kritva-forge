def validate_state_candidate(candidate, module_info):
    """
    Validate structural evidence for an FSM state register.

    This routine DOES NOT assign the final score.

    It only determines

        valid
        confidence
        bonus
        penalty
    """

    structural = module_info.get("structural", {})

    signal = candidate["signal"]

    evidence = set(candidate.get("evidence", []))

    features = candidate.get("features", {})

    required = {

        "always_ff": False,

        "case": False,

        "feedback": False,

        "reset": False,

        "enum": False
    }

    bonus = []

    penalty = []

    #
    # ------------------------------
    # Required Evidence
    # ------------------------------
    #

    if "always_ff" in evidence:
        required["always_ff"] = True

    if "case" in evidence:
        required["case"] = True

    if "feedback" in evidence:
        required["feedback"] = True

    if "reset" in evidence:
        required["reset"] = True

    if "enum" in evidence:
        required["enum"] = True

    #
    # ------------------------------
    # Bonus
    # ------------------------------
    #

    if "state_name" in evidence:
        bonus.append("state_name")

    if "small_width" in evidence:
        bonus.append("small_width")

    if "next_relation" in evidence:
        bonus.append("next_relation")

    if len(features.get("states", [])) >= 2:
        bonus.append("multi_state")

    #
    # ------------------------------
    # Penalty
    # ------------------------------
    #

    lname = signal.lower()

    BAD_SUFFIX = (

        "_cnt",

        "_counter",

        "_addr",

        "_data",

        "_mask",

        "_ptr",

        "_index",

        "_byte",

        "_crc",

        "_sum",

        "_size"
    )

    if lname.endswith(BAD_SUFFIX):

        penalty.append("datapath_name")

    width = features.get("width", 1)

    if width > 16:

        penalty.append("large_width")

    deps = features.get("dependencies", [])

    #
    # Arithmetic usually indicates counters,
    # not FSM state registers.
    #
    if any(

        "+" in str(d)

        or

        "-" in str(d)

        for d in deps

    ):

        penalty.append("arithmetic")

    #
    # ------------------------------
    # Determine validity
    # ------------------------------
    #

    required_count = sum(required.values())

    #
    # Strong FSM
    #
    if required_count >= 4:

        valid = True

        confidence = "high"

    #
    # Typical two-process FSM
    #
    elif required_count == 3:

        valid = True

        confidence = "medium"

    #
    # Weak evidence
    #
    elif required_count == 2 and len(bonus) >= 2:

        valid = True

        confidence = "low"

    else:

        valid = False

        confidence = "reject"

    #
    # Too many penalties?
    #
    if len(penalty) >= 2:

        valid = False

        confidence = "reject"

    candidate["valid"] = valid

    candidate["confidence"] = confidence

    candidate["required"] = required

    candidate["bonus"] = bonus

    candidate["penalty"] = penalty

    return candidate

